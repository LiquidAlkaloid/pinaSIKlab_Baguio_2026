// Revision-matrix export (feature #3). The prototype writes an HTML table with a .doc
// extension, which Word opens directly. The real build will use the `docx` library.

/** One row of the v_revision_matrix view (confirmed items only). */
export interface MatrixRow {
	item_no: number;
	comment: string;
	action_taken: string;
	/** decline_reason, or changed_excerpt when the comment was acted on. */
	action_detail: string;
	page: number | null;
}

const escape = (s: string) =>
	s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

export function downloadMatrix(studentName: string, title: string, rows: MatrixRow[]) {
	const body = rows
		.map(
			(r) =>
				`<tr><td>${r.item_no}</td><td>${escape(r.comment)}</td><td>${escape(r.action_taken)}</td><td>${escape(r.action_detail)}</td><td>${r.page ?? ''}</td></tr>`
		)
		.join('');
	const html = `<html><head><meta charset="utf-8"><style>
body{font-family:Calibri,Arial,sans-serif}
table{border-collapse:collapse;width:100%}
th,td{border:1px solid #444;padding:6px;vertical-align:top;text-align:left}
th{background:#dde4f0}
</style></head><body>
<h2>Revision matrix</h2>
<p><b>Student:</b> ${escape(studentName)}<br><b>Paper:</b> ${escape(title)}</p>
<table><tr><th>No.</th><th>Comment</th><th>Action taken</th><th>What changed, or why not</th><th>Page</th></tr>${body}</table>
<p><i>Generated by MYRACLE (prototype, sample data).</i></p>
</body></html>`;

	const blob = new Blob([html], { type: 'application/msword' });
	const url = URL.createObjectURL(blob);
	const a = document.createElement('a');
	a.href = url;
	a.download = `revision-matrix-${studentName.toLowerCase().replace(/\s+/g, '-')}.doc`;
	a.click();
	URL.revokeObjectURL(url);
}
